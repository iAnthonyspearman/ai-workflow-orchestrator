import fs from "fs";
import path from "path";

function getLocalEnvValue(key) {
  try {
    const envPath = path.join(process.cwd(), ".env.local");

    if (!fs.existsSync(envPath)) {
      return null;
    }

    const envFile = fs.readFileSync(envPath, "utf8");

    const lines = envFile.split(/\r?\n/);

    for (const line of lines) {
      const trimmedLine = line.trim();

      if (!trimmedLine || trimmedLine.startsWith("#")) {
        continue;
      }

      const equalIndex = trimmedLine.indexOf("=");

      if (equalIndex === -1) {
        continue;
      }

      const envKey = trimmedLine.slice(0, equalIndex).trim();
      let envValue = trimmedLine.slice(equalIndex + 1).trim();

      envValue = envValue.replace(/^["']|["']$/g, "");

      if (envKey === key) {
        return envValue;
      }
    }

    return null;
  } catch (error) {
    console.error("Local env read error:", error);
    return null;
  }
}

function getEnvValue(key, fallback = null) {
  return process.env[key] || getLocalEnvValue(key) || fallback;
}

export default async function handler(req, res) {
  if (req.method !== "POST") {
    return res.status(405).json({
      error: "Method not allowed. Use POST."
    });
  }

  try {
    const apiKey = getEnvValue("OPENAI_API_KEY");
    const model = getEnvValue("OPENAI_MODEL", "gpt-4.1-mini");

    if (!apiKey) {
      return res.status(500).json({
        error: "OPENAI_API_KEY is missing.",
        details:
          "The backend could not find OPENAI_API_KEY in process.env or .env.local. Make sure .env.local is in the project root next to package.json."
      });
    }

    const { goal, mode } = req.body || {};

    if (!goal || goal.trim().length < 5) {
      return res.status(400).json({
        error: "Please enter a clear goal or business problem."
      });
    }

    const selectedMode = mode || "Business Workflow";

    const systemPrompt = `
You are an elite AI Workflow Orchestrator for business teams, solution engineers, and technical leaders.

Your job is to turn a user's goal into a practical execution workflow.

Return ONLY valid JSON. No markdown. No extra commentary.

Use this exact JSON structure:

{
  "goalSummary": "",
  "businessContext": "",
  "workflowStrategy": "",
  "nextBestAction": "",
  "timeline": [
    {
      "phase": "",
      "timeframe": "",
      "objective": ""
    }
  ],
  "tasks": [
    {
      "title": "",
      "description": "",
      "category": "",
      "priority": "High | Medium | Low",
      "status": "Pending"
    }
  ],
  "risks": [
    {
      "risk": "",
      "impact": "High | Medium | Low",
      "mitigation": ""
    }
  ],
  "successMetrics": [
    ""
  ]
}

Rules:
- Make the plan practical and business-ready.
- Avoid vague advice.
- Create 6 to 10 tasks.
- Include technical, business, and operational tasks when relevant.
- Make it useful for a Solution Engineer, AI Deployment Engineer, or business leader.
- The output must be valid JSON.
`;

    const userPrompt = `
Mode: ${selectedMode}

User goal or business problem:
${goal}

Create a structured AI workflow execution plan.
`;

    const openAIResponse = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        Authorization: `Bearer ${apiKey}`
      },
      body: JSON.stringify({
        model,
        messages: [
          {
            role: "system",
            content: systemPrompt
          },
          {
            role: "user",
            content: userPrompt
          }
        ],
        temperature: 0.35,
        response_format: {
          type: "json_object"
        }
      })
    });

    const openAIData = await openAIResponse.json();

    if (!openAIResponse.ok) {
      return res.status(openAIResponse.status).json({
        error: "OpenAI API request failed.",
        details:
          openAIData?.error?.message ||
          "Check your API key, billing status, model access, or OpenAI account."
      });
    }

    const rawContent = openAIData.choices?.[0]?.message?.content;

    if (!rawContent) {
      return res.status(500).json({
        error: "No workflow was generated by the model."
      });
    }

    const workflow = JSON.parse(rawContent);

    return res.status(200).json({
      workflow
    });
  } catch (error) {
    console.error("Workflow generation error:", error);

    return res.status(500).json({
      error: "Backend failed while generating the workflow.",
      details: error.message || "Unknown backend error"
    });
  }
}